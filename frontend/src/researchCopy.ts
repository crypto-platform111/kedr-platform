export function researchCopy(text: string, locale: Locale): string {
  if (locale !== "ru") return text;
  if (text.startsWith("Signal on completed bar i;")) {
    const offset = text.match(/open i\+(\d+)/)?.[1] || "2";
    return `Сигнал формируется по завершённой свече i, расчётное исполнение — на открытии i + ${offset}. Между сигналом и исполнением выдерживается задержка в полных свечах; исполнения по сигнальному закрытию нет.`;
  }
  return messages.find(([prefix]) => text.startsWith(prefix))?.[1] || text;
}

